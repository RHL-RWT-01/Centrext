// Package export writes a namespace's user-verified decisions, architecture
// and conventions to read-only Markdown files in a repo (ADR-020, ADR-022).
// It's one-way: files are generated, never imported, and never edited by hand.
package export

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"centrext/internal/application"
	"centrext/internal/domain"
	"centrext/internal/fsutil"
)

// Dir is the export folder, relative to the repo root. It isn't ".centrext/"
// because ".centrext" is the namespace marker file (ADR-017, ADR-022).
const Dir = ".centrext-export"

// header starts every generated file; only files with it are ever removed.
const header = "<!-- Generated by `centrext export`. Don't edit: change it in Centrext, then export again. -->"

// Result lists what changed, relative to the repo root.
type Result struct {
	Written   []string
	Removed   []string
	Unchanged int
}

var typeOrder = map[domain.ContextType]int{domain.TypeDecision: 0, domain.TypeArchitecture: 1, domain.TypeConvention: 2}

var sections = []struct {
	typ   domain.ContextType
	title string
}{{domain.TypeDecision, "Decisions"}, {domain.TypeArchitecture, "Architecture"}, {domain.TypeConvention, "Conventions"}}

// Write makes repoDir/.centrext-export match views: one file per item plus a
// README index. Output is deterministic, so an unchanged namespace produces
// no git diff. Generated files for items no longer exported are removed.
func Write(repoDir string, ns domain.Namespace, views []application.ContextView) (Result, error) {
	var res Result
	sort.SliceStable(views, func(i, j int) bool {
		a, b := views[i], views[j]
		if typeOrder[a.Context.Type] != typeOrder[b.Context.Type] {
			return typeOrder[a.Context.Type] < typeOrder[b.Context.Type]
		}
		if a.Head.Title != b.Head.Title {
			return a.Head.Title < b.Head.Title
		}
		return a.Context.ID < b.Context.ID
	})
	ctxDir := filepath.Join(repoDir, Dir, "context")
	keep := map[string]bool{}
	names := make([]string, len(views))
	for i, v := range views {
		names[i] = FileName(v)
		keep[names[i]] = true
		changed, err := write(filepath.Join(ctxDir, names[i]), renderItem(v))
		if err != nil {
			return res, err
		}
		res.record(filepath.Join(Dir, "context", names[i]), changed)
	}
	entries, err := os.ReadDir(ctxDir)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return res, err
	}
	for _, e := range entries {
		if e.IsDir() || keep[e.Name()] || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		p := filepath.Join(ctxDir, e.Name())
		if b, err := os.ReadFile(p); err == nil && generated(b) {
			if err := os.Remove(p); err != nil {
				return res, err
			}
			res.Removed = append(res.Removed, filepath.Join(Dir, "context", e.Name()))
		}
	}
	changed, err := write(filepath.Join(repoDir, Dir, "README.md"), renderIndex(ns, views, names))
	if err != nil {
		return res, err
	}
	res.record(filepath.Join(Dir, "README.md"), changed)
	return res, nil
}

func (r *Result) record(path string, changed bool) {
	if changed {
		r.Written = append(r.Written, path)
	} else {
		r.Unchanged++
	}
}

func generated(b []byte) bool { return strings.Contains(string(b), header) }

func write(path string, data []byte) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == string(data) {
		return false, nil
	}
	return true, fsutil.WriteAtomic(path, data, 0o644)
}

// FileName is "<slug>-<id tail>.md": readable, and unique even when titles repeat.
func FileName(v application.ContextView) string {
	id := v.Context.ID
	if len(id) > 6 {
		id = id[len(id)-6:]
	}
	return slug(v.Head.Title) + "-" + id + ".md"
}

func slug(s string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(s) {
		if r < 128 && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			b.WriteRune(r)
			dash = false
		} else if !dash && b.Len() > 0 {
			b.WriteByte('-')
			dash = true
		}
		if b.Len() >= 50 {
			break
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		return "item"
	}
	return out
}

func renderItem(v application.ContextView) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "---\nid: %s\nversion: %d\ntype: %s\ntrust: %s\nupdated: %s\n---\n%s\n\n# %s\n\n%s\n",
		v.Context.ID, v.Context.CurrentVersion, v.Context.Type, v.Context.HeadTrust,
		v.Context.UpdatedAt.UTC().Format("2006-01-02"), header, v.Head.Title, strings.TrimSpace(v.Head.Body))
	return []byte(b.String())
}

func renderIndex(ns domain.Namespace, views []application.ContextView, names []string) []byte {
	var b strings.Builder
	b.WriteString("# Shared context\n\n" + header + "\n\n")
	fmt.Fprintf(&b, "A read-only snapshot of the user-verified decisions, architecture and conventions in the Centrext namespace **%s**. ", ns.Name)
	b.WriteString("Treat them as the team's agreed choices. To change one, update it in Centrext and run `centrext export` again.\n")
	if len(views) == 0 {
		b.WriteString("\nNothing is exported yet. Only user-verified items are included; approve items with `centrext review` or `centrext context verify`.\n")
		return []byte(b.String())
	}
	for _, sec := range sections {
		first := true
		for i, v := range views {
			if v.Context.Type != sec.typ {
				continue
			}
			if first {
				fmt.Fprintf(&b, "\n## %s\n\n", sec.title)
				first = false
			}
			fmt.Fprintf(&b, "- [%s](context/%s)\n", v.Head.Title, names[i])
		}
	}
	return []byte(b.String())
}
