package connect

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// writeAtomic writes via a temp file and rename, so readers never see a
// partial file (ADR-016). An existing file keeps its permissions.
func writeAtomic(path string, data []byte, perm os.FileMode) error {
	if fi, err := os.Stat(path); err == nil {
		perm = fi.Mode().Perm()
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp) // no-op after a successful rename
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp, perm); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// readJSON reads a JSON object file. A missing or empty file is an empty object.
func readJSON(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) || (err == nil && len(bytes.TrimSpace(b)) == 0) {
		return map[string]any{}, nil
	}
	if err != nil {
		return nil, err
	}
	m := map[string]any{}
	if err := json.Unmarshal(b, &m); err != nil {
		return nil, fmt.Errorf("%s is not valid JSON (%v); fix it or move it aside, then run connect again", path, err)
	}
	return m, nil
}

// writeJSON writes m to path, keeping a copy of the previous version next to
// it (path + ".centrext-backup") the first time Centrext changes the file.
func writeJSON(path string, m map[string]any, perm os.FileMode) error {
	b, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	b = append(b, '\n')
	if old, err := os.ReadFile(path); err == nil {
		if bytes.Equal(old, b) {
			return nil
		}
		backup := path + ".centrext-backup"
		if _, err := os.Stat(backup); errors.Is(err, os.ErrNotExist) {
			if err := os.WriteFile(backup, old, 0o600); err != nil {
				return err
			}
		}
	}
	return writeAtomic(path, b, perm)
}

// object returns m[key] as an object, creating it if missing.
func object(m map[string]any, key string) (map[string]any, error) {
	switch v := m[key].(type) {
	case nil:
		o := map[string]any{}
		m[key] = o
		return o, nil
	case map[string]any:
		return v, nil
	}
	return nil, fmt.Errorf("%q is not a JSON object", key)
}

// ensureGitignore adds line to dir/.gitignore unless an identical line exists.
func ensureGitignore(dir, line string) (bool, error) {
	path := filepath.Join(dir, ".gitignore")
	b, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	for _, l := range strings.Split(string(b), "\n") {
		if strings.TrimSpace(l) == line {
			return false, nil
		}
	}
	if len(b) > 0 && !bytes.HasSuffix(b, []byte("\n")) {
		b = append(b, '\n')
	}
	b = append(b, []byte("# Generated by Centrext; rewritten when shared context changes\n"+line+"\n")...)
	return true, writeAtomic(path, b, 0o644)
}

// shellQuote quotes s for a POSIX shell command line when needed.
func shellQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n'\"\\$`!*?[]{}()<>|&;#~") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
